import React from 'react';
import {
  Award,
  CheckCircle2,
  Download,
  FileText,
  Play,
  Printer,
  RotateCcw,
  ShieldAlert,
  TrendingUp
} from 'lucide-react';
import { SeverityBadge } from '../../components/SeverityBadge.jsx';

export function MissionDebriefView({
  mission,
  investigationState,
  debriefResult,
  progressionOutcome,
  onReplayMission,
  onNextMission,
  onBackToMenu
}) {
  if (!mission || !debriefResult) return null;

  const { assessment = {}, evidence = [], responseActions = [] } = investigationState || {};

  function handleExportReportJson() {
    const payload = {
      exportType: 'cyberops_report_v1',
      disclaimer:
        'TRAINING SIMULATION REPORT — Generated by CyberOps Simulator from synthetic training data. Not forensic proof.',
      generatedAt: new Date().toISOString(),
      missionId: mission.id,
      missionTitle: mission.title,
      organization: mission.organization,
      overallScore: debriefResult.overallScore,
      grade: debriefResult.grade,
      dimensions: debriefResult.dimensions,
      assessment,
      collectedEvidence: evidence,
      executedResponses: responseActions
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `cyberops-incident-report-${mission.id}.json`;
    a.click();
    URL.revokeObjectURL(url);
  }

  function handlePrintReport() {
    if (typeof window !== 'undefined' && window.print) {
      window.print();
    }
  }

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '18px', maxWidth: '1180px', margin: '0 auto' }}>
      {/* Top Action Bar */}
      <div className="no-print" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: '10px' }}>
        <div style={{ display: 'flex', gap: '8px' }}>
          <button type="button" className="btn" onClick={onBackToMenu}>
            Return to Main Menu
          </button>
          <button type="button" className="btn" onClick={onReplayMission}>
            <RotateCcw size={14} />
            <span>Replay Mission</span>
          </button>
        </div>

        <div style={{ display: 'flex', gap: '8px', flexWrap: 'wrap' }}>
          <button type="button" className="btn" onClick={handlePrintReport}>
            <Printer size={14} />
            <span>Print / Save Report as PDF</span>
          </button>
          <button type="button" className="btn" onClick={handleExportReportJson}>
            <Download size={14} />
            <span>Export Report JSON</span>
          </button>
          {onNextMission && (
            <button type="button" className="btn btn-primary" onClick={onNextMission}>
              <Play size={14} />
              <span>Proceed to Next Mission</span>
            </button>
          )}
        </div>
      </div>

      {/* Hero Grade & Score Card */}
      <section className="panel-elevated" style={{ padding: '22px' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: '20px' }}>
          <div>
            <span className="sim-badge">POST-INCIDENT DEBRIEF &amp; EVALUATION</span>
            <h1 style={{ margin: '6px 0 4px 0', fontSize: '24px' }}>{mission.title} — Debrief</h1>
            <div style={{ color: 'var(--text-secondary)', fontSize: '13.5px' }}>
              Submitted Classification:{' '}
              <strong className="mono">{(assessment.classification || '').replace(/_/g, ' ').toUpperCase()}</strong> •
              Ground Truth:{' '}
              <strong className="mono" style={{ color: 'var(--accent-cyan)' }}>
                {mission.groundTruth.classification.replace(/_/g, ' ').toUpperCase()}
              </strong>
            </div>
          </div>

          <div style={{ display: 'flex', alignItems: 'center', gap: '20px' }}>
            <div style={{ textAlign: 'right' }}>
              <div style={{ fontSize: '12px', color: 'var(--text-secondary)', textTransform: 'uppercase' }}>
                Investigation Score
              </div>
              <div className="mono" style={{ fontSize: '28px', fontWeight: 700, color: 'var(--accent-cyan)' }}>
                {debriefResult.overallScore}%
              </div>
              <div className="mono" style={{ fontSize: '12px', color: 'var(--status-safe)' }}>
                +{progressionOutcome?.netXpGained ?? debriefResult.earnedXp} XP Earned
                {progressionOutcome?.wasReplay && progressionOutcome.netXpGained === 0
                  ? ' (Replay - Previous Best Retained)'
                  : ''}
              </div>
            </div>

            <div
              style={{
                width: '72px',
                height: '72px',
                borderRadius: 'var(--radius-lg)',
                backgroundColor: 'var(--accent-cyan-dim)',
                border: '2px solid var(--accent-cyan)',
                display: 'flex',
                flexDirection: 'column',
                alignItems: 'center',
                justifyContent: 'center'
              }}
            >
              <span style={{ fontSize: '10px', color: 'var(--text-secondary)' }}>GRADE</span>
              <span className="mono" style={{ fontSize: '30px', fontWeight: 700, color: 'var(--accent-cyan)', lineHeight: 1 }}>
                {debriefResult.grade}
              </span>
            </div>
          </div>
        </div>

        {/* Newly Unlocked Achievements */}
        {progressionOutcome?.newlyUnlockedAchievements?.length > 0 && (
          <div
            style={{
              marginTop: '14px',
              padding: '10px 14px',
              backgroundColor: 'rgba(16, 185, 129, 0.12)',
              border: '1px solid rgba(16, 185, 129, 0.4)',
              borderRadius: 'var(--radius-sm)',
              display: 'flex',
              alignItems: 'center',
              gap: '10px',
              flexWrap: 'wrap'
            }}
          >
            <Award size={18} color="var(--status-safe)" />
            <strong style={{ color: '#6ee7b7' }}>New Achievement(s) Unlocked:</strong>
            {progressionOutcome.newlyUnlockedAchievements.map((ach) => (
              <span key={ach.id} className="sev-badge sev-safe">
                ★ {ach.title} (+{ach.xpBonus} XP)
              </span>
            ))}
          </div>
        )}
      </section>

      {/* 6 Score Dimensions Breakdown */}
      <section className="panel">
        <div className="panel-header">
          <h2 className="panel-title">
            <TrendingUp size={15} color="var(--accent-cyan)" />
            <span>Multi-Dimensional Performance Breakdown</span>
          </h2>
        </div>

        <div className="grid-3">
          {Object.entries(debriefResult.dimensions).map(([key, dim]) => {
            const readableTitle = key.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase());
            return (
              <div key={key} className="panel" style={{ backgroundColor: 'var(--bg-input)' }}>
                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
                  <strong>{readableTitle}</strong>
                  <span className="mono" style={{ color: 'var(--accent-cyan)', fontWeight: 700 }}>
                    {dim.score}% <span style={{ fontSize: '11px', color: 'var(--text-muted)' }}>({dim.weight})</span>
                  </span>
                </div>
                <div
                  style={{
                    width: '100%',
                    height: '6px',
                    backgroundColor: 'var(--bg-panel)',
                    borderRadius: '3px',
                    overflow: 'hidden',
                    marginBottom: '8px'
                  }}
                >
                  <div
                    style={{
                      width: `${dim.score}%`,
                      height: '100%',
                      backgroundColor:
                        dim.score >= 80
                          ? 'var(--status-safe)'
                          : dim.score >= 60
                          ? 'var(--sev-medium)'
                          : 'var(--sev-critical)'
                    }}
                  />
                </div>
                <p style={{ margin: 0, fontSize: '12px', color: 'var(--text-secondary)' }}>{dim.explanation}</p>
              </div>
            );
          })}
        </div>
      </section>

      {/* Ground-Truth Walkthrough & Coaching Feedback */}
      <div className="grid-2">
        <section className="panel">
          <div className="panel-header">
            <h2 className="panel-title">
              <CheckCircle2 size={15} color="var(--status-safe)" />
              <span>Intended Analyst Reasoning &amp; Ground Truth</span>
            </h2>
          </div>
          <p style={{ margin: '0 0 12px 0', fontSize: '13.5px', lineHeight: 1.6 }}>
            {debriefResult.intendedReasoning}
          </p>

          <div style={{ fontSize: '12.5px', display: 'grid', gap: '6px' }}>
            <div>
              <strong>Expected Core Evidence IDs:</strong>{' '}
              <span className="mono">{mission.groundTruth.expectedEvidenceIds.join(', ')}</span>
            </div>
            <div>
              <strong>Matched Core Evidence:</strong>{' '}
              <span className="mono" style={{ color: 'var(--status-safe)' }}>
                {debriefResult.matchedCoreEvidence.length > 0
                  ? debriefResult.matchedCoreEvidence.join(', ')
                  : 'None'}
              </span>
            </div>
            {debriefResult.missedEvidenceIds.length > 0 && (
              <div>
                <strong>Missed Indicators:</strong>{' '}
                <span className="mono" style={{ color: 'var(--sev-medium)' }}>
                  {debriefResult.missedEvidenceIds.join(', ')}
                </span>
              </div>
            )}
          </div>
        </section>

        <section className="panel">
          <div className="panel-header">
            <h2 className="panel-title">
              <ShieldAlert size={15} color="var(--sev-medium)" />
              <span>Actionable Improvement Recommendations</span>
            </h2>
          </div>
          <ul style={{ margin: 0, paddingLeft: '18px', display: 'flex', flexDirection: 'column', gap: '8px', fontSize: '13px', color: 'var(--text-secondary)' }}>
            {debriefResult.improvements.map((imp, idx) => (
              <li key={idx}>{imp}</li>
            ))}
          </ul>
        </section>
      </div>

      {/* Printable Formal Incident Report Document */}
      <section className="panel">
        <div className="panel-header">
          <h2 className="panel-title">
            <FileText size={15} color="var(--accent-cyan)" />
            <span>Submitted SOC Incident Report (Simulated Training Record)</span>
          </h2>
          <SeverityBadge severity={assessment.severity || 'medium'} />
        </div>

        <div style={{ fontSize: '12px', color: 'var(--text-muted)', marginBottom: '12px' }}>
          Notice: This report was produced inside the CyberOps Simulator training exercise using synthetic telemetry. It does not constitute real-world forensic proof.
        </div>

        <div className="grid-3" style={{ marginBottom: '12px' }}>
          <div className="panel" style={{ backgroundColor: 'var(--bg-input)', padding: '10px' }}>
            <span className="label">Classification &amp; Confidence</span>
            <div className="mono">
              {(assessment.classification || 'N/A').replace(/_/g, ' ').toUpperCase()} ({assessment.confidence || 'high'})
            </div>
          </div>
          <div className="panel" style={{ backgroundColor: 'var(--bg-input)', padding: '10px' }}>
            <span className="label">Scoped Entities</span>
            <div className="mono">{assessment.affectedEntity || 'N/A'}</div>
          </div>
          <div className="panel" style={{ backgroundColor: 'var(--bg-input)', padding: '10px' }}>
            <span className="label">ATT&amp;CK Techniques Cited</span>
            <div className="mono">
              {(assessment.attackStages || []).length > 0 ? assessment.attackStages.join(', ') : 'None (Benign / N/A)'}
            </div>
          </div>
        </div>

        <div style={{ display: 'grid', gap: '10px', fontSize: '13px' }}>
          <div>
            <strong>Key Findings &amp; Attack Sequence:</strong>
            <div style={{ color: 'var(--text-secondary)', marginTop: '2px' }}>{assessment.keyFindings}</div>
          </div>
          {assessment.scopeSummary && (
            <div>
              <strong>Scope &amp; Impact Summary:</strong>
              <div style={{ color: 'var(--text-secondary)', marginTop: '2px' }}>{assessment.scopeSummary}</div>
            </div>
          )}
          {assessment.remainingUncertainty && (
            <div>
              <strong>Remaining Uncertainty:</strong>
              <div style={{ color: 'var(--text-secondary)', marginTop: '2px' }}>{assessment.remainingUncertainty}</div>
            </div>
          )}
          {assessment.recommendedFollowUp && (
            <div>
              <strong>Recommended Follow-up Actions:</strong>
              <div style={{ color: 'var(--text-secondary)', marginTop: '2px' }}>{assessment.recommendedFollowUp}</div>
            </div>
          )}
        </div>
      </section>
    </div>
  );
}
